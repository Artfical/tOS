static const uint8_t rcon[10] = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

static uint8_t xtime(uint8_t a)
{
    return (a << 1) ^ ((a >> 7) ? 0x1b : 0x00);
}

static uint8_t gmul(uint8_t a, uint8_t b)
{
    uint8_t p = 0;
    int i;
    for (i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        uint8_t hi = a >> 7;
        a = (uint8_t)(a << 1);
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

static void expand_key(const uint8_t key[16], uint8_t rk[176])
{
    int i;
    memcpy(rk, key, 16);
    for (i = 4; i < 44; i++) {
        uint8_t tmp[4];
        tmp[0]=rk[(i-1)*4]; tmp[1]=rk[(i-1)*4+1];
        tmp[2]=rk[(i-1)*4+2]; tmp[3]=rk[(i-1)*4+3];
        if (i % 4 == 0) {
            uint8_t t = tmp[0];
            tmp[0] = sbox[tmp[1]] ^ rcon[i/4-1];
            tmp[1] = sbox[tmp[2]];
            tmp[2] = sbox[tmp[3]];
            tmp[3] = sbox[t];
        }
        rk[i*4]   = rk[(i-4)*4]   ^ tmp[0];
        rk[i*4+1] = rk[(i-4)*4+1] ^ tmp[1];
        rk[i*4+2] = rk[(i-4)*4+2] ^ tmp[2];
        rk[i*4+3] = rk[(i-4)*4+3] ^ tmp[3];
    }
}

/* state is 4x4, column-major: state[row + col*4] */
void aes128_encrypt(const uint8_t key[16], const uint8_t in[16], uint8_t out[16])
{
    uint8_t rk[176], st[16], tmp;
    int r, j;
    expand_key(key, rk);
    for (j = 0; j < 16; j++) st[j] = in[j] ^ rk[j];
    for (r = 1; r <= 10; r++) {
        /* SubBytes */
        for (j = 0; j < 16; j++) st[j] = sbox[st[j]];
        /* ShiftRows: row i shifted left by i */
        tmp=st[1]; st[1]=st[5]; st[5]=st[9]; st[9]=st[13]; st[13]=tmp;
        tmp=st[2]; st[2]=st[10]; st[10]=tmp; tmp=st[6]; st[6]=st[14]; st[14]=tmp;
        tmp=st[15]; st[15]=st[11]; st[11]=st[7]; st[7]=st[3]; st[3]=tmp;
        /* MixColumns (skip on last round) */
        if (r < 10) {
            for (j = 0; j < 4; j++) {
                uint8_t a0=st[j*4], a1=st[j*4+1], a2=st[j*4+2], a3=st[j*4+3];
                st[j*4]   = xtime(a0) ^ (xtime(a1)^a1) ^ a2 ^ a3;
                st[j*4+1] = a0 ^ xtime(a1) ^ (xtime(a2)^a2) ^ a3;
                st[j*4+2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3)^a3);
                st[j*4+3] = (xtime(a0)^a0) ^ a1 ^ a2 ^ xtime(a3);
            }
        }
        /* AddRoundKey */
        for (j = 0; j < 16; j++) st[j] ^= rk[r*16+j];
    }
    for (j = 0; j < 16; j++) out[j] = st[j];
}

void aes128_decrypt(const uint8_t key[16], const uint8_t in[16], uint8_t out[16])
{
    uint8_t rk[176], st[16], tmp;
    int r, j;
    expand_key(key, rk);
    for (j = 0; j < 16; j++) st[j] = in[j] ^ rk[10*16+j];
    for (r = 9; r >= 0; r--) {
        /* InvShiftRows */
        tmp=st[13]; st[13]=st[9]; st[9]=st[5]; st[5]=st[1]; st[1]=tmp;
        tmp=st[2]; st[2]=st[10]; st[10]=tmp; tmp=st[6]; st[6]=st[14]; st[14]=tmp;
        tmp=st[3]; st[3]=st[7]; st[7]=st[11]; st[11]=st[15]; st[15]=tmp;
        /* InvSubBytes */
        for (j = 0; j < 16; j++) st[j] = inv_sbox[st[j]];
        /* AddRoundKey */
        for (j = 0; j < 16; j++) st[j] ^= rk[r*16+j];
        /* InvMixColumns (skip on first decryption round, which is last encrypt round=0) */
        if (r > 0) {
            for (j = 0; j < 4; j++) {
                uint8_t a0=st[j*4], a1=st[j*4+1], a2=st[j*4+2], a3=st[j*4+3];
                st[j*4]   = gmul(0x0e,a0)^gmul(0x0b,a1)^gmul(0x0d,a2)^gmul(0x09,a3);
                st[j*4+1] = gmul(0x09,a0)^gmul(0x0e,a1)^gmul(0x0b,a2)^gmul(0x0d,a3);
                st[j*4+2] = gmul(0x0d,a0)^gmul(0x09,a1)^gmul(0x0e,a2)^gmul(0x0b,a3);
                st[j*4+3] = gmul(0x0b,a0)^gmul(0x0d,a1)^gmul(0x09,a2)^gmul(0x0e,a3);
            }
        }
    }
    for (j = 0; j < 16; j++) out[j] = st[j];
}
