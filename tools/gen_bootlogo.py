#!/usr/bin/env python3
"""The boot screen's logo: third_party/ui/artfical-logo.png (black on white), cropped to the
mark, scaled to 420 px wide and kept as 8-bit coverage, run-length coded into
kernel/display/bootlogo.c. Run again after changing the picture."""
import os
from PIL import Image, ImageOps
HERE = os.path.dirname(os.path.abspath(__file__))
src = Image.open(os.path.join(HERE, '..', 'third_party', 'ui', 'artfical-logo.png'))
if src.mode == 'RGBA':
    cov = src.getchannel('A')                    # the mark on a transparent background
else:
    cov = ImageOps.invert(src.convert('L'))      # dark ink on white
cov = cov.crop(cov.getbbox())
W = 420
H = round(cov.height * W / cov.width)
cov = cov.resize((W, H), Image.LANCZOS)
px = list(cov.getdata())
# runs: (count, value) pairs, count 1..255
rle = []
i = 0
while i < len(px):
    v = px[i]; n = 1
    while i + n < len(px) and px[i + n] == v and n < 255: n += 1
    rle += [n, v]; i += n
with open(os.path.join(HERE, '..', 'kernel', 'display', 'bootlogo.c'), 'w') as f:
    f.write('/* generated by tools/gen_bootlogo.py from third_party/ui/artfical-logo.png */\n#include <stdint.h>\n')
    f.write(f'const int boot_logo_w = {W}, boot_logo_h = {H};\nconst uint32_t boot_logo_rle_len = {len(rle)};\n')
    f.write('const uint8_t boot_logo_rle[] = {\n')
    for k in range(0, len(rle), 24):
        f.write('    ' + ', '.join(str(b) for b in rle[k:k + 24]) + ',\n')
    f.write('};\n')
print('boot logo', W, 'x', H, len(rle), 'bytes')
