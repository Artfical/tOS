#!/usr/bin/env python3
"""
Builds kernel/display/ui_classic.c: the icons tOS had before the WhiteSur icon theme (build 576 and older), as an
extra icon pack the "Classic" theme switches to. Only the pictures that differ from today's are kept.

    python3 tools/gen_classic_icons.py OLD_ui_assets.c NEW_ui_assets.c OUT_ui_classic.c

(OLD_ui_assets.c is kernel/display/ui_assets.c of commit 6106c7c^.)
"""
import re, sys, zlib

def load(path):
    s = open(path).read()
    packed = bytes(int(x) for x in re.search(r'ui_blob\[\] = \{(.*?)\};', s, re.S).group(1).replace('\n', ' ').split(',') if x.strip())
    blob = zlib.decompress(packed, -15)
    imgs = {}
    for name, w, h, off in re.findall(r'\{"([^"]+)", (\d+), (\d+), (\d+)u\}', s.split('ui_images[]')[1]):
        w, h, off = int(w), int(h), int(off)
        n = w * h * (3 if name == 'wallpaper' else 4)
        imgs[name] = (w, h, blob[off:off + n])
    return imgs

old, new = load(sys.argv[1]), load(sys.argv[2])
keep = [(n, v) for n, v in old.items() if n != 'wallpaper' and (n not in new or new[n] != v) and n.startswith(('icon', 'doc', 'rec_', 'app', 'avatar'))]
blob = bytearray(); table = []
for n, (w, h, d) in keep:
    table.append((n, w, h, len(blob))); blob.extend(d)
packed = zlib.compressobj(9, zlib.DEFLATED, -15); packed = packed.compress(bytes(blob)) + packed.flush()
with open(sys.argv[3], 'w') as f:
    f.write('/* Generated by tools/gen_classic_icons.py -- do not edit. The icons before WhiteSur. */\n#include "ui_assets.h"\n\n')
    f.write(f'const uint32_t ui_classic_raw_len = {len(blob)}u;\nconst uint32_t ui_classic_len = {len(packed)}u;\nconst uint8_t ui_classic_blob[] = {{\n')
    for i in range(0, len(packed), 24): f.write('  ' + ','.join(str(b) for b in packed[i:i + 24]) + ',\n')
    f.write('};\n\nconst ui_image_t ui_classic_images[] = {\n')
    for n, w, h, o in table: f.write(f'    {{"{n}", {w}, {h}, {o}u}},\n')
    f.write(f'}};\nconst int ui_classic_count = {len(table)};\n')
print(len(keep), 'icons,', len(blob), 'raw,', len(packed), 'compressed')
