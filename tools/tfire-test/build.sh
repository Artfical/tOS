#!/bin/sh
# Builds tFire's engine for the host (gcc, glibc), for tools/tfire-test/*.c: /tmp/tfire_engine
set -e
cd "$(dirname "$0")/../.."
N=third_party/netsurf
O=${TFIRE_HOST_OBJ:-/tmp/tfire_hostobj}
mkdir -p $O
if [ ! -f $O/libns.a ]; then
    find $N -name "*.c" | grep -v "css_property_parser_gen\|/test/\|autogenerated-element-type.c" | while read f; do
        case $f in
        $N/libparserutils*) inc="-I$N/libparserutils/include -I$N/libparserutils/src";;
        $N/libwapcaplet*) inc="-I$N/libwapcaplet/include";;
        $N/libhubbub*) inc="-I$N/libhubbub/include -I$N/libhubbub/src -I$N/libparserutils/include";;
        $N/libcss*) inc="-I$N/libcss/include -I$N/libcss/src -I$N/libparserutils/include -I$N/libwapcaplet/include";;
        esac
        gcc -O1 -g -w -std=gnu99 -DWITHOUT_ICONV_FILTER -DNDEBUG $inc -c $f -o $O/$(echo $f | tr / _).o
    done
    ar rcs $O/libns.a $O/*.o
fi
INC="-I$N/libparserutils/include -I$N/libwapcaplet/include -I$N/libhubbub/include -I$N/libcss/include -Ikernel/tfire"
gcc -O1 -g -Wall -Wextra -Wno-unused-parameter -std=gnu99 -DTFIRE_HOST $INC \
    kernel/tfire/dom.c kernel/tfire/style.c kernel/tfire/layout.c tools/tfire-test/engine_host.c $O/libns.a -o /tmp/tfire_engine
