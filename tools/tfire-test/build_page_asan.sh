#!/bin/sh
# Builds tFire's whole engine for the host (32-bit, like tOS), for page_host.c: /tmp/tfire_page
set -e
cd "$(dirname "$0")/../.."
N=third_party/netsurf
Q=third_party/quickjs
O=${TFIRE_HOST_OBJ:-/tmp/tfire_hostobj32}
mkdir -p /tmp/tfire_inc32/asm && echo "#include <asm-generic/errno.h>" > /tmp/tfire_inc32/asm/errno.h
mkdir -p $O
if [ ! -f $O/libns.a ]; then
    find $N -name "*.c" | grep -v "css_property_parser_gen\|/test/\|autogenerated-element-type.c" | while read f; do
        case $f in
        $N/libparserutils*) inc="-I$N/libparserutils/include -I$N/libparserutils/src";;
        $N/libwapcaplet*) inc="-I$N/libwapcaplet/include";;
        $N/libhubbub*) inc="-I$N/libhubbub/include -I$N/libhubbub/src -I$N/libparserutils/include";;
        $N/libcss*) inc="-I$N/libcss/include -I$N/libcss/src -I$N/libparserutils/include -I$N/libwapcaplet/include";;
        esac
        gcc -m32 -isystem /tmp/tfire_inc32 -O1 -g -w -std=gnu99 -DWITHOUT_ICONV_FILTER -DNDEBUG $inc -c $f -o $O/$(echo $f | tr / _).o
    done
    ar rcs $O/libns.a $O/*.o
fi
if [ ! -f $O/libqjs.a ]; then
    for f in quickjs libregexp libunicode cutils dtoa; do
        gcc -m32 -isystem /tmp/tfire_inc32 -O2 -g -w -std=gnu99 -D_GNU_SOURCE -DTOS_TFIRE -DCONFIG_VERSION='"2025-09-13"' -c $Q/$f.c -o $O/qjs_$f.o
    done
    ar rcs $O/libqjs.a $O/qjs_*.o
fi
if [ ! -f $O/libwebp.a ]; then
    for f in third_party/libwebp/src/dec/*.c third_party/libwebp/src/utils/*.c third_party/libwebp/src/dsp/*.c; do
        gcc -m32 -isystem /tmp/tfire_inc32 -O2 -w -Ithird_party/libwebp -c $f -o $O/webp_$(basename $f .c).o
    done
    ar rcs $O/libwebp.a $O/webp_*.o
fi
INC="-I$N/libparserutils/include -I$N/libwapcaplet/include -I$N/libhubbub/include -I$N/libcss/include -I$Q -Ikernel/tfire -Ikernel/net -Ikernel/display -Ithird_party/nanosvg -Ithird_party/libwebp"
as --32 kernel/tfire/js_prelude.s -o $O/prelude.o
gcc -m32 -isystem /tmp/tfire_inc32 -O1 -g -fsanitize=address -Wall -Wextra -Wno-unused-parameter -std=gnu99 -DTFIRE_HOST $INC \
    kernel/tfire/dom.c kernel/tfire/style.c kernel/tfire/layout.c kernel/tfire/engine.c kernel/tfire/js.c kernel/tfire/images.c \
    tools/tfire-test/page_host.c $O/prelude.o $O/libqjs.a $O/libns.a $O/libwebp.a -lm -lpthread -fsanitize=address -fno-omit-frame-pointer -o /tmp/tfire_page_asan
